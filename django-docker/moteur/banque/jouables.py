def boucle(variable, debut, fin, corps, pas=None):
    b = pour(variable, debut, fin, corps)
    if pas:
        b["pas"] = pas
    return b


def iteration(pid, question, variable, numero, boucle_n=None):
    p = point(pid, question, variable, "iteration", numero)
    if boucle_n:
        p["moment"]["boucle"] = boucle_n
    return p


def J(cle, titre, notion, niveau, difficulte, enonce, objectifs, src, *, entrees=None, blocs, points, indices,
      python, **reste):
    return {
        "fiche": fiche(cle, titre, notion, niveau, difficulte, enonce, objectifs, src, indices=indices, **reste),
        "exercice": {
            "notion": notion if notion in ("variables", "conditions", "boucles", "tableaux") else reste["secondaires"][0],
            "titre": titre,
            "enonce": enonce,
            "entrees": entrees or {},
            "blocs": blocs,
            "points_controle": points,
            "indices": list(indices),
            "sorties_langages": {"python": python},
        },
    }


